const resources = { en: { translation: en }, bn: { translation: bn } }

const i18nInstance = i18next.createInstance()
void i18nInstance.use(initReactI18next).init({
  resources,
  lng: 'en',
  fallbackLng: 'en',
  keySeparator: false,
  interpolation: { escapeValue: false },
})

export type Locale = 'en' | 'bn'

interface LocaleState {
  locale: Locale
  setLocale: (locale: Locale) => void
  /** Translate a dictionary key. Unknown keys fall back to the key itself. */
  t: (key: MessageKey) => string
}

const Context = createContext<LocaleState>({ locale: 'en', setLocale: () => {}, t: (key) => en[key] ?? String(key) })
const STORAGE_KEY = 'library-locale'

function storedLocale(): Locale {
  if (typeof window === 'undefined') return 'en'
  return window.localStorage.getItem(STORAGE_KEY) === 'bn' ? 'bn' : 'en'
}

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(storedLocale)
  const { t: translate, i18n } = useTranslation()

  useEffect(() => {
    window.localStorage.setItem(STORAGE_KEY, locale)
    document.documentElement.lang = locale === 'bn' ? 'bn' : 'en'
    document.title = locale === 'bn' ? 'পাতাপথ লাইব্রেরি · লাইব্রেরি ম্যানেজমেন্ট' : 'Leafline Library · Library management'
    void i18n.changeLanguage(locale)
  }, [locale, i18n])

  const setLocale = useCallback((value: Locale) => setLocaleState(value), [])
  const t = useCallback((key: MessageKey) => {
    const value = translate(String(key))
    return typeof value === 'string' && value && value !== String(key) ? value : (en[key] ?? String(key))
  }, [translate])

  const value = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t])
  return <I18nextProvider i18n={i18nInstance}><Context.Provider value={value}>{children}</Context.Provider></I18nextProvider>
}

export const useLocale = () => useContext(Context)
